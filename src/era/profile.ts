import * as fs from 'fs';
import * as path from 'path';
import defaultProfile from './profiles/emuera-1824-ee55.json';
/**
 * Era engine profile: the declared dialect of one Emuera build.
 *
 * An Era game splits meaning across three layers — ERB scripts, ontology CSVs,
 * and the engine. Only the engine knows which CSV names which built-in variable
 * and which instruction dispatches by a string built at run time. Those two
 * facts are needed by the CSV extractor, the ERB extractor AND the cross-layer
 * resolver, so they live here as data instead of being restated in each.
 *
 * Profiles are generated by `scripts/era/build-engine-profile.mjs` from a
 * decompiled engine and checked in under `profiles/`. A game that ships a
 * different Emuera build gets its own profile; nothing else changes.
 */

/** How a built-in variable is shaped and where its slot names come from. */
export interface EraVariable {
  /** Variable name as written in ERB (`ABL`, `TEQUIP`, `ITEMPRICE`). */
  name: string;
  valueType: 'int' | 'string';
  /** Index depth: 0 = scalar, 1 = `VAR:i`, 2 = `VAR:i:j`, 3 = `VAR:i:j:k`. */
  dimensions: number;
  /** True when the first index selects a character (`ABL:CHARA:slot`). */
  perCharacter: boolean;
  /** Engine-enforced read-only (`ITEMPRICE`, `RAND`, `__LINE__`). */
  readOnly: boolean;
  /**
   * `save` persists in the save file, `local`/`global` do not. Used to separate
   * persistent game facts from interpreter state when reporting a behavior's
   * reads and writes.
   */
  scope: 'save' | 'local' | 'global';
  /**
   * Ontology CSV that names this variable's slots, as spelled in the engine
   * (`ABL.CSV`); match against disk case-insensitively. `null` means the
   * variable is indexed by number only, so every slot is an unnamed slot.
   * `chara*.csv` marks per-character instance data, which is not ontology.
   */
  backingCsv: string | null;
  /** Argument position the CSV name occupies; 1 for per-character variables. */
  nameArgIndex: number | null;
}

/**
 * A built-in instruction. `kind` says how (and whether) it reaches another
 * function; `isForm` says the target name is interpolated at run time, which is
 * the single bit that makes a call site invisible to grep.
 */
export interface EraInstruction {
  name: string;
  /**
   * `call` reaches an `@FUNCTION`, `callf` an expression-callable `#FUNCTION`,
   * `goto` a `$LABEL` inside the current function, `event` the fixed EVENT*
   * set, `other` does not transfer control.
   */
  kind: 'call' | 'callf' | 'goto' | 'event' | 'other';
  isForm: boolean;
  isJump: boolean;
  isTry: boolean;
  isTryCatch: boolean;
}

export interface EraEngineProfile {
  schemaVersion: 1;
  /** Profile identity, e.g. `emuera-1824-ee55`. */
  id: string;
  /** `source` = derived from a decompiled engine, `declared` = hand-written. */
  derived: 'source' | 'declared';
  engine: {
    path: string;
    sha256: string;
    fileVersion: string | null;
    productVersion: string | null;
  };
  /**
   * Emuera reads UTF-8 first and falls back to the ANSI code page. Games ship
   * either, so decoding tries `primary` then `fallback`.
   */
  encoding: { primary: string; fallback: string };
  /** Ontology CSV file names the engine loads, in load order. */
  csvFiles: string[];
  variables: EraVariable[];
  instructions: EraInstruction[];
  /**
   * Built-in expression functions (`MAX(a, b)`, `CSVNAME(chara)`). They share
   * the `name(args)` shape with game-defined `#FUNCTION`s, so the extractor
   * needs this list to avoid emitting a call to a game function that does not
   * exist for every built-in it sees.
   */
  methods: string[];
  /**
   * Character-sheet (`Chara*.csv`) key table, from the engine's
   * `toCharacterTemplate`. The row key decides which variable the row
   * initializes, and the mapping holds real surprises: `基礎` writes MAXBASE,
   * and `珠` is named through palam.csv. `identity` keys carry who the sheet
   * is (番号, 名前, …); `ignored` keys the engine itself discards.
   */
  chara?: {
    keys: Record<string, string>;
    identity: string[];
    ignored: string[];
  };
}

/** Indexed views of a profile, built once and shared by every extractor. */
export interface EraProfileIndex {
  profile: EraEngineProfile;
  /** Variable name -> definition. */
  variables: Map<string, EraVariable>;
  /** Instruction name -> definition. */
  instructions: Map<string, EraInstruction>;
  /** Built-in expression function names. */
  methods: Set<string>;
  /** Chara-sheet row key -> variable it initializes (`素質` -> `TALENT`). */
  charaKeys: Map<string, string>;
  /** Chara-sheet identity keys (`番号`, `名前`, …). */
  charaIdentityKeys: Set<string>;
  /** Chara-sheet keys the engine itself discards (`助手`, `ISASSI`). */
  charaIgnoredKeys: Set<string>;
  /** Lowercased CSV basename -> the variables it names. */
  csvToVariables: Map<string, EraVariable[]>;
  /** Lowercased CSV basename set, for `is this file ontology` checks. */
  ontologyCsvNames: Set<string>;
}


/**
 * Engine profile loading.
 *
 * Callers ask for `getEraProfile()` and get a fully indexed profile or a clear
 * throw; there is no "profile missing" state to handle at every call site. The
 * shipped default is the engine era-ym actually runs (Emuera 1.824 EEv55); a
 * project on a different build points `CODEGRAPH_ERA_PROFILE` at an
 * absolute path to a generated JSON profile.
 */

/** Wildcard CSVs describe instance data, not ontology. */
const NON_ONTOLOGY_CSV = /\*/;
let cached: EraProfileIndex | null = null;

/** Load and index the active engine profile. Cached for the process. */
export function getEraProfile(): EraProfileIndex {
  if (cached) return cached;
  const requested = process.env.CODEGRAPH_ERA_PROFILE?.trim();
  let profile = defaultProfile as EraEngineProfile;
  if (requested) {
    if (!path.isAbsolute(requested)) {
      throw new Error('CODEGRAPH_ERA_PROFILE must be an absolute path to a JSON profile');
    }
    try {
      profile = JSON.parse(fs.readFileSync(requested, 'utf8')) as EraEngineProfile;
    } catch (error) {
      throw new Error(
        'Era engine profile could not be read from ' + requested + ': ' +
        (error instanceof Error ? error.message : String(error))
      );
    }
  }
  if (profile.schemaVersion !== 1) {
    throw new Error('Era engine profile has unsupported schemaVersion ' + profile.schemaVersion);
  }
  cached = indexProfile(profile);
  return cached;
}

/** Reset the cache. Tests use this to swap profiles; production never calls it. */
export function resetEraProfileCache(): void {
  cached = null;
}

/** Build the lookup maps every extractor and the resolver share. */
export function indexProfile(profile: EraEngineProfile): EraProfileIndex {
  const variables = new Map<string, EraVariable>();
  for (const v of profile.variables) variables.set(v.name, v);

  const instructions = new Map(profile.instructions.map((i) => [i.name, i]));
  const methods = new Set(profile.methods ?? []);
  const charaKeys = new Map(Object.entries(profile.chara?.keys ?? {}));
  const charaIdentityKeys = new Set(profile.chara?.identity ?? []);
  const charaIgnoredKeys = new Set(profile.chara?.ignored ?? []);

  const csvToVariables = new Map<string, EraVariable[]>();
  for (const v of profile.variables) {
    if (!v.backingCsv || NON_ONTOLOGY_CSV.test(v.backingCsv)) continue;
    const key = v.backingCsv.toLowerCase();
    const list = csvToVariables.get(key);
    if (list) list.push(v);
    else csvToVariables.set(key, [v]);
  }

  // Every CSV the engine loads is ontology, including ones no variable names
  // through (STRNAME.CSV names STR); indexing them all keeps `who defines this
  // row` answerable even where the naming path is indirect.
  const ontologyCsvNames = new Set<string>();
  for (const f of profile.csvFiles) ontologyCsvNames.add(f.toLowerCase());
  for (const key of csvToVariables.keys()) ontologyCsvNames.add(key);

  return {
    profile,
    variables,
    instructions,
    methods,
    charaKeys,
    charaIdentityKeys,
    charaIgnoredKeys,
    csvToVariables,
    ontologyCsvNames,
  };
}

/**
 * Is this path one of the ontology CSVs the engine loads?
 *
 * Matching is by basename, case-insensitively: the engine looks in a single
 * `csvDir`, and games spell the files inconsistently (`Abl.csv` on disk,
 * `ABL.CSV` in the engine). The path must be exactly `CSV/<name>` at the
 * project root, which is where Emuera looks and nowhere else. A looser rule
 * would claim an unrelated `Item.csv` in another project, and would also pull
 * in the tables that ship inside a game's optional patch directories, which
 * the engine never loads.
 */
export function isEraOntologyCsv(filePath: string, index?: EraProfileIndex): boolean {
  const normalized = filePath.replace(/\\/g, '/');
  const slash = normalized.indexOf('/');
  if (slash < 0 || normalized.slice(0, slash).toLowerCase() !== 'csv') return false;
  const base = normalized.slice(normalized.lastIndexOf('/') + 1);
  if (normalized.indexOf('/', slash + 1) >= 0) return false; // no nesting under CSV/
  if (!base.toLowerCase().endsWith('.csv')) return false;
  const lower = base.toLowerCase();
  // GameBase.csv is not an ontology table, but it is where the engine
  // vocabulary is anchored, so it has to be indexed too.
  if (lower === 'gamebase.csv') return true;
  let profileIndex: EraProfileIndex;
  try {
    profileIndex = index ?? getEraProfile();
  } catch {
    return false;
  }
  return profileIndex.ontologyCsvNames.has(lower);
}

/**
 * A character sheet: `Chara*.csv` anywhere under the game's `CSV/`.
 *
 * The engine enumerates `CHARA*.CSV` case-insensitively and, with
 * `サブディレクトリを検索する` on (era-ym has it on), descends into
 * subdirectories, so `CSV/chara/1000_win東方/Chara1000 あなた.csv` is as much
 * a loaded file as `CSV/Chara500.csv`. These are instance data, not ontology:
 * they get their own extractor that turns rows into writes.
 */
export function isEraCharaCsv(filePath: string): boolean {
  const normalized = filePath.replace(/\\/g, '/').toLowerCase();
  if (!normalized.startsWith('csv/')) return false;
  const base = normalized.slice(normalized.lastIndexOf('/') + 1);
  return base.startsWith('chara') && base.endsWith('.csv');
}
